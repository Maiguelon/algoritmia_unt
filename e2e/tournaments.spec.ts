import {test,expect} from '@playwright/test';
test('torneo con población, curva y fuentes; Regional 2026 pendiente',async({page})=>{
 await page.goto('/torneos/regional-2025/');
 await expect(page.getByRole('heading',{level:1})).toContainText('2025');
 await expect(page.getByText('equipos participantes')).toBeVisible();
 await expect(page.getByRole('heading',{name:'Cuántos equipos hicieron cuántos AC'})).toBeVisible();
 await expect(page.locator('.stat').first()).toContainText('201');
 await expect(page.locator('tbody tr')).toHaveCount(12);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/torneos/');
 await expect(page.getByText('Regional 2026 pendiente de publicación de problemas.',{exact:true})).toBeVisible();
 await page.goto('/torneos/tap-2026/');
 await expect(page.locator('.page-heading .eyebrow')).toHaveCount(0);
 await expect(page.locator('.tournament-judge')).toContainText('Gym 106682 · 14 problemas');
 await expect(page.getByRole('link',{name:'Abrir Gym 106682 en Codeforces (nueva pestaña)'})).toHaveAttribute('href','https://codeforces.com/gym/106682');
 await expect(page.locator('.stat').nth(1)).toContainText('55');
 await expect(page.locator('.stat').nth(1)).toContainText('cupos argentinos al Regional');
 await expect(page.locator('.stat').nth(2)).toContainText('4');
 const qualification=page.getByRole('region',{name:'Qué hacía falta para clasificar'});
 await expect(qualification).toBeVisible();
 await expect(qualification.getByRole('article',{name:'Último equipo en el corte directo'})).toContainText('Testing');
 await expect(qualification.locator('.qualification-paths li')).toHaveCount(2);
 await expect(qualification.locator('.qualification-paths')).toContainText('Clasificación indirecta');
 await expect(qualification).toContainText('242');
 await expect(qualification).toContainText('DP de juegos');
 await expect(qualification).toContainText('Greedy de secuencias');
 await expect(qualification.locator('.preparation-step')).toHaveCount(2);
 await expect(qualification.locator('.preparation-step').nth(1).getByRole('link')).toHaveText(['C','L']);
 await expect(qualification.locator('.qualification-level')).toContainText('Salto regional');
 await expect(qualification.locator('.qualification-routes')).toHaveCount(0);
 await expect(qualification.getByRole('link',{name:'L. Luana\'s Album'})).toHaveAttribute('href','/problemas/tap-2026-l/');
 const navigation=page.getByRole('navigation',{name:'Secciones del torneo'});
 for(const [name,id] of [['Estadísticas','estadisticas'],['Problemas','problemas'],['Tucumán','tucuman']]) {
   await navigation.getByRole('link',{name,exact:true}).click();
   await expect(page).toHaveURL(new RegExp(`#${id}$`));
   await expect(page.locator(`#${id}`)).toBeInViewport();
 }
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/torneos/regional-2026/');
 await expect(page.locator('.tournament-judge')).toHaveCount(0);
 await expect(page.locator('.stat').nth(1)).toContainText('—');
 await expect(page.locator('.qualification-analysis')).toHaveCount(0);
});
